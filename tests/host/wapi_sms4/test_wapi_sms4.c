/* Host L2 oracle smoke for SMS4 block helpers (T17). */
#include <stdio.h>
#include <string.h>

#include "host_wapi_sms4_oracle.h"

int main(void)
{
	const u8 key[16] = { 0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef,
			     0xfe, 0xdc, 0xba, 0x98, 0x76, 0x54, 0x32, 0x10 };
	const u8 plain[16] = { 0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef,
			       0xfe, 0xdc, 0xba, 0x98, 0x76, 0x54, 0x32, 0x10 };
	const u8 expect[16] = { 0x68, 0x1e, 0xdf, 0x34, 0xd2, 0x06, 0x96, 0x5e,
				0x86, 0xb3, 0xe9, 0x4f, 0x53, 0x6e, 0x42, 0x46 };
	u32 rk[32];
	u8 out[16];

	host_sms4_key_ext(key, rk, HOST_SMS4_ENCRYPT);
	host_sms4_crypt(plain, out, rk);
	if (memcmp(out, expect, 16)) {
		fprintf(stderr, "FAIL gbt32907-example1-ecb\n");
		return 1;
	}
	printf("ok gbt32907-example1-ecb\n");
	printf("wapi_sms4 oracle smoke passed\n");
	return 0;
}
